import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir, hostname } from "node:os";
import path from "node:path";
import { lanAddress, randomToken } from "./util.js";

export interface DshRuntime {
  command: string;
  argsPrefix: string[];
  env: NodeJS.ProcessEnv;
  description: string;
}

export interface AgentConfig {
  version: string;
  hostName: string;
  home: string;
  token: string;
  port: number;
  bind: string;
  publicUrl: string;
  roots: string[];
  dshHome: string;
  dshProfile: string;
  dshProvider: string;
  dshModel: string;
  dshPatchPath: string;
  syncDir: string;
  syncUrl?: string;
  syncRoom?: string;
  syncKey?: string;
  syncToken?: string;
  dshRuntime: DshRuntime;
  dshRuntimeError?: string;
  codexBin: string;
  claudeModel: string;
}

const VERSION = "0.6.0";

function ensureDir(dir: string): void {
  mkdirSync(dir, { recursive: true, mode: 0o700 });
}

function readOrCreateToken(home: string): string {
  const fromEnv = process.env.AGENT_REMOTE_TOKEN?.trim();
  if (fromEnv) return fromEnv;

  const tokenPath = path.join(home, "token");
  if (existsSync(tokenPath)) {
    const existing = readFileSync(tokenPath, "utf8").trim();
    if (existing) return existing;
  }
  const token = randomToken(32);
  writeFileSync(tokenPath, `${token}\n`, { mode: 0o600 });
  return token;
}

function assertTokenPart(value: string, name: string): string {
  if (!/^[A-Za-z0-9._/-]+$/.test(value)) {
    throw new Error(`${name} contains unsupported characters: ${JSON.stringify(value)}`);
  }
  return value;
}

function which(command: string): string | undefined {
  try {
    const finder = process.platform === "win32" ? "where" : "which";
    const output = execFileSync(finder, [command], {
      encoding: "utf8",
      windowsHide: true,
    }).trim();
    return output.split(/\r?\n/).map((line) => line.trim()).find(Boolean);
  } catch {
    return undefined;
  }
}

export function resolveDshRuntime(): DshRuntime {
  const explicit = process.env.DSH_BIN?.trim();
  if (explicit) {
    return {
      command: explicit,
      argsPrefix: [],
      env: {},
      description: `DSH_BIN=${explicit}`,
    };
  }

  const onPath = which("dsh");
  if (onPath) {
    return {
      command: onPath,
      argsPrefix: [],
      env: {},
      description: onPath,
    };
  }

  if (process.platform === "darwin") {
    const appPath = process.env.DSH_APP_PATH?.trim() || "/Applications/DeepSeek Harness.app";
    const electron = path.join(appPath, "Contents/MacOS/DeepSeek Harness");
    const asar = path.join(appPath, "Contents/Resources/app.asar");
    const binJs = path.join(
      appPath,
      "Contents/Resources/app.asar/dsh/node_modules/@deepseek-ai/dsh/lib/bin.js",
    );
    // `binJs` lives inside the asar archive, so it is not visible to a plain
    // `existsSync` here. Electron (ELECTRON_RUN_AS_NODE=1) resolves it at spawn
    // time; only the archive itself needs to exist on disk.
    if (existsSync(electron) && existsSync(asar)) {
      return {
        command: electron,
        argsPrefix: [binJs],
        env: { ELECTRON_RUN_AS_NODE: "1" },
        description: `${appPath} (Electron as Node)`,
      };
    }
  }

  const platformHint = process.platform === "win32"
    ? "Install the DSH CLI on Windows (npm install -g @deepseek-ai/dsh) and put dsh on PATH, or set DSH_BIN. You can still use Codex or Claude without DSH."
    : "Install DSH, put dsh on PATH, or set DSH_BIN / DSH_APP_PATH.";
  throw new Error(`DeepSeek Harness CLI not found. ${platformHint}`);
}

export function writeDshPatch(patchPath: string, provider: string, model: string): void {
  const content = `# Generated by agent-remote agentd. Do not edit.
- id: acp
  name: "@deepseek-ai/dsh-acp"
  config:
    provider: ${provider}
    model: ${model}
`;
  writeFileSync(patchPath, content, { mode: 0o600 });
}

export function loadConfig(): AgentConfig {
  const home = process.env.AGENT_REMOTE_HOME?.trim() || path.join(homedir(), ".agent-remote");
  ensureDir(home);
  const token = readOrCreateToken(home);

  const port = Number(process.env.AGENT_REMOTE_PORT ?? 8787);
  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    throw new Error(`Invalid AGENT_REMOTE_PORT: ${process.env.AGENT_REMOTE_PORT}`);
  }

  const bind = process.env.AGENT_REMOTE_BIND?.trim() || "0.0.0.0";
  const roots = (process.env.AGENT_REMOTE_ROOTS?.trim() || homedir())
    .split(path.delimiter)
    .map((root) => root.trim())
    .filter(Boolean);

  const dshHome = process.env.DSH_HOME?.trim() || path.join(homedir(), ".dsh");
  // DSH sets DSH_PROFILE=desktop inside its own Electron process. Do not
  // inherit that; only an explicit AGENT_REMOTE_DSH_PROFILE selects a profile.
  const dshProfile = process.env.AGENT_REMOTE_DSH_PROFILE?.trim() || "acp";
  const dshProvider = assertTokenPart(
    process.env.DSH_PROVIDER?.trim() || "deepseek-account",
    "DSH_PROVIDER",
  );
  const dshModel = assertTokenPart(
    process.env.DSH_MODEL?.trim() || "deepseek-flash",
    "DSH_MODEL",
  );
  const dshPatchPath = path.join(home, "dsh-acp.patch.yml");
  writeDshPatch(dshPatchPath, dshProvider, dshModel);
  const syncDir = process.env.AGENT_REMOTE_SYNC_DIR?.trim() || path.join(home, "sessions");
  ensureDir(syncDir);
  const syncUrl = process.env.AGENT_REMOTE_SYNC_URL?.trim() || undefined;
  const syncRoom = process.env.AGENT_REMOTE_SYNC_ROOM?.trim() || "default";
  const syncKey = process.env.AGENT_REMOTE_SYNC_KEY?.trim() || undefined;
  const syncToken = process.env.AGENT_REMOTE_SYNC_TOKEN?.trim() || undefined;
  if (syncUrl && !syncKey) {
    throw new Error("AGENT_REMOTE_SYNC_KEY is required when AGENT_REMOTE_SYNC_URL is set");
  }
  if (!/^[A-Za-z0-9_-]{1,64}$/.test(syncRoom)) {
    throw new Error("AGENT_REMOTE_SYNC_ROOM must match [A-Za-z0-9_-]{1,64}");
  }

  const publicUrl =
    process.env.AGENT_REMOTE_PUBLIC_URL?.trim() || `ws://${lanAddress()}:${port}/ws`;
  const codexBin = process.env.CODEX_BIN?.trim() || "codex";
  const claudeModel = process.env.AGENT_REMOTE_CLAUDE_MODEL?.trim() || "sonnet";

  let dshRuntime: DshRuntime;
  let dshRuntimeError: string | undefined;
  try {
    dshRuntime = resolveDshRuntime();
  } catch (error) {
    dshRuntime = { command: "dsh", argsPrefix: [], env: {}, description: "unavailable" };
    dshRuntimeError = error instanceof Error ? error.message : String(error);
  }

  return {
    version: VERSION,
    hostName: hostname(),
    home,
    token,
    port,
    bind,
    publicUrl,
    roots,
    dshHome,
    dshProfile,
    dshProvider,
    dshModel,
    dshPatchPath,
    syncDir,
    syncUrl,
    syncRoom,
    syncKey,
    syncToken,
    dshRuntime,
    dshRuntimeError,
    codexBin,
    claudeModel,
  };
}
